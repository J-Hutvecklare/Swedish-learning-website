const LS_UI_LANG = "sv-learn-ui-lang";
const LS_THEME = "sv-learn-theme-v1";
function getSavedTheme(){
  const v = localStorage.getItem(LS_THEME);
  return v === "dark" ? "dark" : "light";
}
function applyTheme(theme){
  const mode = theme === "dark" ? "dark" : "light";
  document.documentElement.setAttribute("data-theme", mode);
  localStorage.setItem(LS_THEME, mode);
  const label = mode === "dark" ? (typeof t === "function" ? t("themeToLight") : "Light") : (typeof t === "function" ? t("themeToDark") : "Dark");
  const icon = mode === "dark" ? "☀️" : "🌙";
  document.querySelectorAll(".btn-theme").forEach(btn=>{
    btn.textContent = icon;
    btn.setAttribute("aria-label", typeof t === "function" ? t("themeToggle") : "Toggle theme");
    btn.title = label;
  });
}
function toggleTheme(){
  const next = getSavedTheme() === "dark" ? "light" : "dark";
  applyTheme(next);
}

