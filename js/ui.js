function t(key){
  const lang = state.uiLang === "en" ? "en" : "zh";
  return (I18N[lang] && I18N[lang][key]) || I18N.zh[key] || key;
}
function meaningOf(w){ return state.uiLang==="en" ? (w.english||w.chinese) : w.chinese; }
function exampleTrOf(w){ return state.uiLang==="en" ? (w.exampleEn||w.exampleZh||"") : (w.exampleZh||""); }
function hasForms(w){
  const f = (w && w.forms != null) ? String(w.forms).trim() : "";
  return !!f && f !== "—" && f !== "–" && f !== "-" && f.toLowerCase() !== "n/a";
}
function formsHint(w){ return hasForms(w) ? esc(w.forms) : ""; }
function norm(s){ return (s||"").trim().toLowerCase().normalize("NFC").replace(/\s+/g," "); }
function esc(s){ return String(s).replace(/&/g,"&amp;").replace(/</g,"&lt;").replace(/>/g,"&gt;").replace(/"/g,"&quot;"); }
/* ========== TTS ========== */
function speak(text){
  if(!window.speechSynthesis){ alert("Speech synthesis not supported."); return; }
  speechSynthesis.cancel();
  const u=new SpeechSynthesisUtterance(text);
  u.lang="sv-SE"; u.rate=0.9;
  const v=speechSynthesis.getVoices().find(x=>x.lang==="sv-SE"||x.lang.startsWith("sv"));
  if(v) u.voice=v;
  speechSynthesis.speak(u);
}
